# positive_input.py — Повторный ввод до положительного числа

# Ввод первого числа и счётчик попыток
number = int(input("Введите положительное число: "))
rejected = 0

# Цикл повторного ввода, пока число не станет положительным
while number <= 0:
    rejected += 1
    number = int(input("Повторите ввод: "))

# Вывод результатов
print(f"Квадрат: {number ** 2}")
print(f"Отклонено попыток: {rejected}")
