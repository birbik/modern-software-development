# predict.py — Вычисление и проверка прогнозов арифметических выражений

print("=== Проверка прогнозов выражений ===")

# Выражение 1
expr1 = 2 + 3 * 4
print(f"1) 2 + 3 * 4 = {expr1}")

# Выражение 2
expr2 = (2 + 3) * 4
print(f"2) (2 + 3) * 4 = {expr2}")

# Выражение 3
expr3 = 17 // 5
print(f"3) 17 // 5 = {expr3}")

# Выражение 4
expr4 = 17 % 5
print(f"4) 17 % 5 = {expr4}")

# Выражение 5
expr5 = -7 // 2
print(f"5) -7 // 2 = {expr5}")
