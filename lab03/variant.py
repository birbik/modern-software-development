# variant.py — Вариант 2: Заполненность хранилища
# Диапазоны категорий:
# 0–49: Свободно
# 50–89: Мало места
# 90–100: Почти заполнено
# При выходе за границы 0–100: Ошибка диапазона

# Ввод процента заполненности хранилища
percent = int(input("Введите заполненность хранилища (0–100): "))

# Определение категории
if percent < 0 or percent > 100:
    print("Ошибка диапазона")
elif percent <= 49:
    print("Свободно")
elif percent <= 89:
    print("Мало места")
else:
    print("Почти заполнено")
