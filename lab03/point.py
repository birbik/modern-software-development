# point.py — Проверка принадлежности точки прямоугольнику
# Прямоугольник: 0 <= x <= 5 и 0 <= y <= 3

# Ввод координат точки
x = float(input("Введите координату x: "))
y = float(input("Введите координату y: "))

# Проверка принадлежности прямоугольнику
if 0 <= x <= 5 and 0 <= y <= 3:
    print("Внутри или на границе")
else:
    print("Снаружи")
