# leap_year.py — Проверка года на високосность
# Правило: делится на 400, либо делится на 4 и не делится на 100

# Ввод года
year = int(input("Введите год (1–9999): "))

# Проверка диапазона и определение високосности
if year < 1 or year > 9999:
    print("Ошибка диапазона")
else:
    is_leap = year % 400 == 0 or (year % 4 == 0 and year % 100 != 0)
    if is_leap:
        print("Да")
    else:
        print("Нет")
